import type { PlayerRatings } from '../models/player';

export type ConditionKind = 'injury' | 'illness';

export type ConditionRarity = 'common' | 'uncommon' | 'rare' | 'ultra_rare';

export type ConditionSeverity =
  | 'day_to_day'
  | 'short_il'
  | 'long_il'
  | 'season_ending'
  | 'career_ending_risk';

export type ConditionCategory =
  | 'arm_elbow_shoulder'
  | 'legs_soft_tissue'
  | 'bone_joint'
  | 'concussion_neuro'
  | 'respiratory_viral'
  | 'gi_internal'
  | 'womens_health'
  | 'mens_health'
  | 'complex_oncology';

export type ConditionSexScope = 'all' | 'male' | 'female';

export interface HealthConditionDefinition {
  id: string;
  name: string;
  kind: ConditionKind;
  rarity: ConditionRarity;
  category: ConditionCategory;
  applicableTo: ConditionSexScope;
  severity: ConditionSeverity;
  canPlayThrough: boolean;
  minGamesOut: number;
  maxGamesOut: number;
  statPenalties: Partial<Record<keyof PlayerRatings, number>>;
  description: string;
  comebackBoost?: boolean;
}

