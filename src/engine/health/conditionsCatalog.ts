/** Returns the built-in catalog merged with any custom user-supplied rare conditions. */
export function getAllHealthConditions(
  customConditions: readonly HealthConditionDefinition[] = [],
): readonly HealthConditionDefinition[] {
  if (customConditions.length === 0) return HEALTH_CONDITIONS_CATALOG;
  return [...HEALTH_CONDITIONS_CATALOG, ...customConditions];
}

export function getHealthConditionById(
  conditionId: string,
  customConditions: readonly HealthConditionDefinition[] = [],
): HealthConditionDefinition | undefined {
  return getAllHealthConditions(customConditions).find((c) => c.id === conditionId);
}
